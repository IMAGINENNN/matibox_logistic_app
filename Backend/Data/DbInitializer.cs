    public static async Task SeedAsync(IServiceProvider serviceProvider)
    {
        using var scope = serviceProvider.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        var roleManager = scope.ServiceProvider.GetRequiredService<RoleManager<IdentityRole>>();
        var userManager = scope.ServiceProvider.GetRequiredService<UserManager<ApplicationUser>>();

        await db.Database.MigrateAsync();

        // Ensure "AspNetUsers" has Color & Live Location columns, and "Cars" + "CarAssignments" tables exist
        await db.Database.ExecuteSqlRawAsync(@"
            ALTER TABLE ""AspNetUsers"" ADD COLUMN IF NOT EXISTS ""Color"" character varying(30) DEFAULT '#276EF1';
            ALTER TABLE ""AspNetUsers"" ADD COLUMN IF NOT EXISTS ""LastLatitude"" double precision NULL;
            ALTER TABLE ""AspNetUsers"" ADD COLUMN IF NOT EXISTS ""LastLongitude"" double precision NULL;
            ALTER TABLE ""AspNetUsers"" ADD COLUMN IF NOT EXISTS ""LocationUpdatedAt"" timestamp with time zone NULL;
            ALTER TABLE ""AspNetUsers"" ADD COLUMN IF NOT EXISTS ""IsOnline"" boolean NOT NULL DEFAULT FALSE;

            CREATE TABLE IF NOT EXISTS ""Cars"" (
                ""Id"" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ""Name"" character varying(150) NOT NULL,
                ""NumberPlate"" character varying(50) NOT NULL,
                ""DriverId"" text NULL REFERENCES ""AspNetUsers""(""Id"") ON DELETE SET NULL
            );
            CREATE INDEX IF NOT EXISTS ""IX_Cars_DriverId"" ON ""Cars"" (""DriverId"");

            CREATE TABLE IF NOT EXISTS ""CarAssignments"" (
                ""Id"" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ""CarId"" integer NOT NULL REFERENCES ""Cars""(""Id"") ON DELETE CASCADE,
                ""DriverId"" text NOT NULL REFERENCES ""AspNetUsers""(""Id"") ON DELETE CASCADE,
                ""AssignedAt"" timestamp with time zone NOT NULL DEFAULT NOW()
            );
            CREATE UNIQUE INDEX IF NOT EXISTS ""IX_CarAssignments_CarId_DriverId"" ON ""CarAssignments"" (""CarId"", ""DriverId"");
        ");

        // 1. Seed Roles (Admin, Dispatcher, Driver)
        string[] roles = ["Admin", "Dispatcher", "Driver"];
        foreach (var role in roles)
        {
            if (!await roleManager.RoleExistsAsync(role))
            {
                await roleManager.CreateAsync(new IdentityRole(role));
            }
        }

        // 2. Seed Admin User & Ensure Password is "admin"
        var adminEmail = "admin@matibox.no";
        var adminUser = await userManager.FindByEmailAsync(adminEmail);
        if (adminUser == null)
        {
            adminUser = new ApplicationUser
            {
                UserName = adminEmail,
                Email = adminEmail,
                EmailConfirmed = true,
                Name = "Matibox Dispatch Admin",
                Contact = "+47 22 10 20 30",
                Car = null,
                Color = "#276EF1"
            };
            var res = await userManager.CreateAsync(adminUser, "admin");
            if (res.Succeeded)
            {
                await userManager.AddToRoleAsync(adminUser, "Admin");
            }
        }
        else
        {
            if (!await userManager.CheckPasswordAsync(adminUser, "admin"))
            {
                adminUser.PasswordHash = userManager.PasswordHasher.HashPassword(adminUser, "admin");
                adminUser.SecurityStamp = Guid.NewGuid().ToString();
                await userManager.UpdateAsync(adminUser);
            }
        }

        // 3. Seed Driver Users
        var driver1Email = "ola@matibox.no";
        var driver1 = await userManager.FindByEmailAsync(driver1Email);
        if (driver1 == null)
        {
            driver1 = new ApplicationUser
            {
                UserName = driver1Email,
                Email = driver1Email,
                EmailConfirmed = true,
                Name = "Ola Nordmann",
                Contact = "+47 912 34 567",
                Car = "VW ID.Buzz Cargo (EV 48291)",
                Color = "#276EF1"
            };
            var res = await userManager.CreateAsync(driver1, "Driver123!");
            if (res.Succeeded)
            {
                await userManager.AddToRoleAsync(driver1, "Driver");
            }
        }
        else if (string.IsNullOrWhiteSpace(driver1.Color))
        {
            driver1.Color = "#276EF1";
            await userManager.UpdateAsync(driver1);
        }

        var driver2Email = "kari@matibox.no";
        var driver2 = await userManager.FindByEmailAsync(driver2Email);
        if (driver2 == null)
        {
            driver2 = new ApplicationUser
            {
                UserName = driver2Email,
                Email = driver2Email,
                EmailConfirmed = true,
                Name = "Kari Hansen",
                Contact = "+47 987 65 432",
                Car = "Ford E-Transit (EV 91044)",
                Color = "#A855F7"
            };
            var res = await userManager.CreateAsync(driver2, "Driver123!");
            if (res.Succeeded)
            {
                await userManager.AddToRoleAsync(driver2, "Driver");
            }
        }
        else if (string.IsNullOrWhiteSpace(driver2.Color) || driver2.Color == "#276EF1")
        {
            driver2.Color = "#A855F7";
            await userManager.UpdateAsync(driver2);
        }

        // 4. Seed Initial Cars if Empty & Migrate Legacy Car.DriverId into CarAssignments
        if (!await db.Cars.AnyAsync())
        {
            var car1 = new Car { Name = "VW ID.Buzz Cargo", NumberPlate = "EV 48291" };
            var car2 = new Car { Name = "Ford E-Transit", NumberPlate = "EV 91044" };
            var car3 = new Car { Name = "Mercedes eVito", NumberPlate = "EV 55310" };
            db.Cars.AddRange(car1, car2, car3);
            await db.SaveChangesAsync();

            if (driver1 != null)
            {
                db.CarAssignments.Add(new CarAssignment { CarId = car1.Id, DriverId = driver1.Id });
            }
            if (driver2 != null)
            {
                db.CarAssignments.Add(new CarAssignment { CarId = car2.Id, DriverId = driver2.Id });
            }
            await db.SaveChangesAsync();
        }
        else
        {
            var legacyCarsWithDriver = await db.Cars
                .Where(c => c.DriverId != null)
                .ToListAsync();

            foreach (var c in legacyCarsWithDriver)
            {
                var exists = await db.CarAssignments
                    .AnyAsync(ca => ca.CarId == c.Id && ca.DriverId == c.DriverId);
                if (!exists && !string.IsNullOrEmpty(c.DriverId))
                {
                    db.CarAssignments.Add(new CarAssignment
                    {
                        CarId = c.Id,
                        DriverId = c.DriverId,
                        AssignedAt = DateTime.UtcNow
                    });
                }
                c.DriverId = null;
            }
            if (legacyCarsWithDriver.Count > 0)
            {
                await db.SaveChangesAsync();
            }
        }

        // 5. Remove Legacy Test Kindergartens if present
        var legacyTestItems = await db.Kindergartens
            .Where(k => LegacyTestKindergartenNames.Contains(k.Name))
            .ToListAsync();

        if (legacyTestItems.Count > 0)
        {
            db.Kindergartens.RemoveRange(legacyTestItems);
            await db.SaveChangesAsync();
        }

        // 6. Seed or Sync Real Kindergartens with Exact Verified Coordinates (keeping original Address text untouched)
        var canonicalList = BuildRealKindergartens();
        var existingKindergartens = await db.Kindergartens.ToListAsync();

        if (existingKindergartens.Count == 0)
        {
            db.Kindergartens.AddRange(canonicalList);
            await db.SaveChangesAsync();
        }
        else
        {
            bool anyUpdated = false;
            foreach (var canonical in canonicalList)
            {
                var match = existingKindergartens.FirstOrDefault(k => k.Name == canonical.Name);
                if (match != null)
                {
                    if (Math.Abs(match.Latitude - canonical.Latitude) > 0.000001 ||
                        Math.Abs(match.Longitude - canonical.Longitude) > 0.000001 ||
                        match.GoogleMapsUrl != canonical.GoogleMapsUrl)
                    {
                        match.Latitude = canonical.Latitude;
                        match.Longitude = canonical.Longitude;
                        match.GoogleMapsUrl = canonical.GoogleMapsUrl;
                        anyUpdated = true;
                    }
                }
            }

            if (anyUpdated)
            {
                await db.SaveChangesAsync();
            }
        }

        // 7. Ensure Today's Delivery Assignments Exist for All Kindergartens
        var today = DateOnly.FromDateTime(DateTime.UtcNow.AddHours(1));
        var existingKindergartenIdsToday = await db.DeliveryAssignments
            .Where(d => d.DeliveryDate == today)
            .Select(d => d.KindergartenId)
            .ToListAsync();

        var allKindergartenIds = await db.Kindergartens
            .OrderBy(k => k.Time)
            .ThenBy(k => k.Name)
            .Select(k => k.Id)
            .ToListAsync();

        var missingIds = allKindergartenIds.Except(existingKindergartenIdsToday).ToList();
        if (missingIds.Count > 0)
        {
            foreach (var kId in missingIds)
            {
                db.DeliveryAssignments.Add(new DeliveryAssignment
                {
                    KindergartenId = kId,
                    DriverId = null,
                    DeliveryDate = today,
                    SequenceOrder = 0,
                    IsDelivered = false,
                    DeliveredAt = null
                });
            }

            await db.SaveChangesAsync();
        }
    }

    private static Kindergarten CreateKg(
        string name,
        string contact,
        string address,
        string time,
        int total,
        double lat,
        double lng)
    {
        var latStr = lat.ToString(CultureInfo.InvariantCulture);
        var lngStr = lng.ToString(CultureInfo.InvariantCulture);
        return new Kindergarten
        {
            Name = name,
            Contact = contact,
            Address = address,
            Time = time,
            Total = total,
            Latitude = lat,
            Longitude = lng,
            GoogleMapsUrl = $"https://www.google.com/maps/dir/?api=1&destination={latStr},{lngStr}"
        };
    }

